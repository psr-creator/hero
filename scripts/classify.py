COMPILED = [(re.compile(p), a, b) for p, a, b in RULES]

from verified import VERIFIED
VERIFIED_N = {norm(k): v for k, v in VERIFIED.items()}
OVERRIDES.update(VERIFIED)
OVERRIDES = {norm(k): v for k, v in OVERRIDES.items()}

def classify(name):
    n = norm(name)
    src = "Web-verified" if n in VERIFIED_N else "Name-derived"
    if n in OVERRIDES:
        i, s2, c = OVERRIDES[n]
        return (i, s2, c, src)
    for rx, ind, sub in COMPILED:
        if rx.search(n):
            return (ind, sub, "Medium", src)
    return ("Unclassified", "No industry signal in the name", "Low", src)

