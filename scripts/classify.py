    w.writerow(['Company Name','Industry','Sub-Industry / Activity','Confidence','Source','Rows in source list'])
    for nm in sorted(seen, key=lambda s: norm(s)):
        ind, sub, conf, src = classify(nm)
        w.writerow([nm, ind, sub, conf, src, seen[nm]])

